"""Sanity checks on the raw runs of experiments E1-E3; exit code 1 if any check fails.

    python scripts/check_results.py [--results results]

Reads results/e1|e2|e3/runs.csv (regenerated by the experiment commands, not committed):
- normalized_makespan >= 1 - 1e-9 on every completed run (the lower bound bounds complete
  schedules only; partial runs are counted and reported separately);
- E1 (homogeneous, p = 0, all four schedulers are work-conserving there): normalized_makespan
  <= 2 - 1/k + 1e-9, a consequence of Graham's bound T <= W/k + (1 - 1/k) CP <= (2 - 1/k) LB;
- E1 and E2: completion rate 1.0;
- E3: number of partial runs per failure probability (informational);
- E3: per instance group, either all schedulers completed or none (survivorship check);
- E1 fork-join, k in {2, 4}: which term of the lower bound is binding (informational).

The derived numbers are written to results/checks.json (committed), so docs/results.md can
quote them although runs.csv itself is not committed.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from collections import Counter, defaultdict
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from dagsched.experiments import SummaryError, read_runs
from dagsched.experiments.summarize import Run

TOLERANCE = 1e-9


def _status(ok: bool) -> str:
    return "OK  " if ok else "FAIL"


def check_lower_bound(name: str, runs: list[Run]) -> bool:
    done = [run for run in runs if run.completed]
    bad = [run for run in done if run.normalized_makespan < 1 - TOLERANCE]
    lowest = min((run.normalized_makespan for run in done), default=float("nan"))
    print(f"[{_status(not bad)}] {name}: normalized_makespan >= 1 - 1e-9 on {len(done)} "
          f"completed runs (min {lowest:.6f}, violations {len(bad)})")
    partial = [run for run in runs if not run.completed]
    if partial:
        below = sum(1 for run in partial if run.normalized_makespan < 1 - TOLERANCE)
        print(f"       {name}: {len(partial)} partial runs not checked ({below} of them below 1)")
    return not bad


def check_graham(runs: list[Run]) -> bool:
    ok = True
    off_grid = [run for run in runs if run.failure_p != 0 or run.speeds_kind != "homogeneous"]
    if off_grid:
        print(f"[FAIL] e1: {len(off_grid)} runs are not homogeneous with p = 0")
        ok = False
    for k in sorted({run.k for run in runs}):
        selected = [run for run in runs if run.k == k and run.completed]
        bound = 2 - 1 / k
        worst = max(run.normalized_makespan for run in selected)
        passed = worst <= bound + TOLERANCE
        ok = ok and passed
        print(f"[{_status(passed)}] e1: k={k:>2}: max normalized_makespan {worst:.6f} <= "
              f"2 - 1/k = {bound:.6f} ({len(selected)} runs)")
    return ok


def check_completion(name: str, runs: list[Run]) -> bool:
    done = sum(1 for run in runs if run.completed)
    ok = done == len(runs)
    print(f"[{_status(ok)}] {name}: completion rate {done}/{len(runs)} = {done / len(runs):.4f}")
    return ok


def report_partial(runs: list[Run]) -> list[dict[str, Any]]:
    totals = Counter(run.failure_p for run in runs)
    partial = Counter((run.failure_p, run.speeds_kind) for run in runs if not run.completed)
    rows = []
    for p in sorted(totals):
        homogeneous = partial[(p, "homogeneous")]
        heterogeneous = partial[(p, "heterogeneous")]
        print(f"[INFO] e3: p={p:<4}: {homogeneous + heterogeneous} partial of {totals[p]} runs "
              f"(homogeneous {homogeneous}, heterogeneous {heterogeneous})")
        rows.append({"failure_p": p, "runs": totals[p], "partial": homogeneous + heterogeneous,
                     "homogeneous": homogeneous, "heterogeneous": heterogeneous})
    return rows


def check_completion_consistency(runs: list[Run]) -> tuple[bool, dict[str, int]]:
    """Within one instance group (graph instance, workers, p, seeds) the schedulers that
    completed must be all of them or none: with common random numbers and a worker-independent
    p every scheduler faces the same attempt fates, so permanent failures cannot depend on the
    scheduler. A violation would mean the completed-run means compare different instances."""
    groups: dict[tuple[Any, ...], dict[str, bool]] = defaultdict(dict)
    for run in runs:
        groups[run.instance][run.scheduler] = run.completed
    violations = sum(1 for outcome in groups.values() if 0 < sum(outcome.values()) < len(outcome))
    ok = violations == 0
    print(f"[{_status(ok)}] e3: completed schedulers are all-or-none in {len(groups)} instance "
          f"groups (violations {violations})")
    return ok, {"groups": len(groups), "violations": violations}


def _read_raw(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def bound_terms(rows: list[dict[str, str]], family: str = "fork_join",
                ks: tuple[int, ...] = (2, 4)) -> list[dict[str, Any]]:
    """Which term of LB = max(W/k, CP) is binding, per (k, duration distribution).

    Counted per run (all schedulers of an instance share its bound, so the fractions equal the
    fractions over graph instances). "work" means LB equals W/k, "path" that it equals CP;
    an exact tie would count for both.
    """
    counts: dict[tuple[int, str], Counter] = defaultdict(Counter)
    for row in rows:
        k = int(row["k"])
        if row["graph_family"] != family or k not in ks:
            continue
        bound = float(row["lower_bound"])
        dist = json.loads(row["graph_params"])["durations"]["dist"]
        key = (k, dist)
        counts[key]["runs"] += 1
        counts[key]["work"] += math.isclose(bound, float(row["total_work"]) / k, rel_tol=1e-12)
        counts[key]["path"] += math.isclose(bound, float(row["critical_length"]), rel_tol=1e-12)
    result = []
    for (k, dist), c in sorted(counts.items()):
        entry = {"k": k, "dist": dist, "runs": c["runs"], "work_term": c["work"],
                 "path_term": c["path"], "fraction_work": c["work"] / c["runs"],
                 "fraction_path": c["path"] / c["runs"]}
        print(f"[INFO] e1: {family} k={k} {dist}: lower bound = W/k in "
              f"{entry['fraction_work']:.3f}, = CP in {entry['fraction_path']:.3f} of "
              f"{c['runs']} runs")
        result.append(entry)
    return result


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=Path("results"))
    args = parser.parse_args(argv)
    runs: dict[str, list[Run]] = {}
    for name in ("e1", "e2", "e3"):
        try:
            runs[name] = read_runs(args.results / name / "runs.csv")
        except SummaryError as exc:
            print(f"[FAIL] {name}: {exc}")
            return 1
        print(f"{name}: {len(runs[name])} runs")
    ok = True
    for name, experiment_runs in runs.items():  # no short-circuit: report every check
        ok = check_lower_bound(name, experiment_runs) and ok
    ok = check_graham(runs["e1"]) and ok
    ok = check_completion("e1", runs["e1"]) and ok
    ok = check_completion("e2", runs["e2"]) and ok
    consistent, completion = check_completion_consistency(runs["e3"])
    ok = consistent and ok
    derived = {
        "source": "scripts/check_results.py on results/e1|e2|e3/runs.csv",
        "e3_completion": completion,
        "e3_partial_by_p": report_partial(runs["e3"]),
        "e1_fork_join_bound_terms": bound_terms(_read_raw(args.results / "e1" / "runs.csv")),
    }
    out = args.results / "checks.json"
    out.write_text(json.dumps(derived, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    print("ALL CHECKS PASSED" if ok else "SOME CHECKS FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
